import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import test from 'node:test';
const slug='php2shell-sicherheitsluecke-webseite';
const route=`de/blog/${slug}/`;
const canonical=`https://www.vibeperform.com/${route}`;
const load=path=>readFile(new URL(`../dist/${path}`,import.meta.url),'utf8');
test('PHP2Shell article is published, discoverable and attributed with a live inquiry form',async()=>{
 const html=await load(`${route}index.html`);
 assert.doesNotMatch(html,/<meta name="robots" content="[^"]*noindex|class="kn-draft"|class="bq-preview"/);
 assert.match(html,/<meta property="article:published_time" content="2026-10-23"/);
 assert.ok(html.includes(`rel="canonical" href="${canonical}"`));
 assert.ok(html.includes(`rel="alternate" type="text/markdown" href="${canonical}index.md"`));
 assert.match(html,/data-blog-questionnaire data-preview="false"/);
 assert.match(html,/name="contentOwner"/);
 assert.match(html,/name="updateObstacle"/);
 assert.doesNotMatch(html,/currentPresence|projectInterest/);
 assert.doesNotMatch(html,/class="sv-lead"/);
 assert.match(html,/<meta name="description" content="PHP2Shell verständlich erklärt:/);
 const schema=JSON.parse(html.match(/<script type="application\/ld\+json">([^<]+)<\/script>/)[1]);
 assert.equal(schema['@type'],'BlogPosting');
 assert.equal(schema.author['@type'],'Person');
 assert.equal(schema.author.name,'Marlon Dietrich');
 assert.equal(schema.author.url,'https://www.vibeperform.com/de/ueber-uns/');
 assert.equal(schema.datePublished,'2026-10-23');
 assert.equal(schema.dateModified,'2026-10-23');
 assert.equal(schema.url,canonical);
 assert.equal(schema.image.url,'https://www.vibeperform.com/blog/php2shell/php2shell-og-1200x630.jpg');
 for(const path of ['sitemap.xml','llms.txt','llms-full.txt','de/blog/index.html','de/blog/index.md']) assert.ok((await load(path)).includes(slug),`${path} advertises published article`);
 const md=await load(`${route}index.md`);
 assert.ok(md.includes(canonical));
 assert.ok(md.includes('Autor: Marlon Dietrich'));
 assert.ok(md.includes('Datum: 2026-10-23'));
});
